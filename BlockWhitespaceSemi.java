public class BlockWhitespaceSemi {
    public static void main(String[] args) {
        System.out.println("세미콜론, 블럭, 공백에 대해서");
        // ";"은 논리적으로 한 명령 문장이 끝날 때 사용. 반드시...(*)
        // { ... } : 블럭(중괄호)은 하나의 영역으로 묶여진 부분으로
        // 여러 명령 문장들이 복합적으로 사용하는 영역을 구분.
        System.out.println("여러 명령 줄을 실행할 수 있음.");

        // 공백(Whitespace) : 코드를 보기 좋게(가독성 있게) 만들어 줌.
    }

}
