package Day2;

public class IntvalueExample {
    public static void main(String[] args) {
        int decimalValue = 7;
        int binValue = 0b1000_0101;
        int octalValue = 070;
        int hexaValue = 0xFEFE;

        System.out.println("10진수 7은 : " + decimalValue);
        System.out.println("2진수 1000_1010은 : " + binValue);
        System.out.println("8진수 70은 : " + octalValue);
        System.out.println("16진수 FEFE은 : " + hexaValue);

    }
}
